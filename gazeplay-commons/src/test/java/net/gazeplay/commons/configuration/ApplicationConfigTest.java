package net.gazeplay.commons.configuration;

import org.junit.jupiter.api.Test;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Properties;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

class ApplicationConfigTest {

    private static String withoutDateLine(byte[] stored) {
        // Properties.store writes the date on the second line
        String text = new String(stored, StandardCharsets.ISO_8859_1);
        return text.replaceFirst("(?m)^#[^\\n]*\\d{4}\\r?\\n", "");
    }

    /**
     * GazePlay.properties is a persistent format: the file must be written exactly as java.util.Properties (used by the
     * former Owner implementation) writes it, escapes included.
     */
    @Test
    void shouldWriteTheFileAsJavaUtilProperties() throws IOException {
        Properties properties = new Properties();
        properties.setProperty("CSS_FILE", "builtin:GREEN");
        properties.setProperty("FILE_DIR", "C:\\Users\\Marie Dupont\\GazePlay\\files");
        properties.setProperty("USER_NAME", "Zoé");
        properties.setProperty("FAVORITE_GAMES", "a,b");

        ByteArrayOutputStream expected = new ByteArrayOutputStream();
        properties.store(expected, "Automatically generated by GazePlay");
        ByteArrayOutputStream actual = new ByteArrayOutputStream();
        new ApplicationConfig(properties).store(actual, "Automatically generated by GazePlay");

        assertEquals(withoutDateLine(expected.toByteArray()), withoutDateLine(actual.toByteArray()));
    }

    @Test
    void shouldRemoveTheKeyWhenTheValueIsNull() {
        Properties properties = new Properties();
        properties.setProperty("USER_NAME", "someone");
        ApplicationConfig config = new ApplicationConfig(properties);

        config.setProperty("USER_NAME", null);

        assertNull(config.getProperty("USER_NAME"));
    }

    @Test
    void shouldNotShareTheInitialProperties() {
        Properties properties = new Properties();
        ApplicationConfig config = new ApplicationConfig(properties);

        config.setProperty("USER_NAME", "someone");

        assertNull(properties.getProperty("USER_NAME"));
        assertEquals("someone", config.getProperty("USER_NAME"));
    }
}
